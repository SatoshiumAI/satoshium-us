def _safe(val: Any, fallback: str = "N/A") -> str:
    """Return a string representation of val, or fallback if None/empty."""
    if val is None or str(val).strip() == "":
        return fallback
    return str(val)


def _h(val: Any, fallback: str = "N/A") -> str:
    """HTML-safe string — passes through _safe then HTML-escapes special chars."""
    return _html.escape(_safe(val, fallback))


def _evidence_table_md(refs: List[Dict]) -> str:
    if not refs:
        return "_No evidence items listed._\n"
    rows = ["| # | ID | Title | Type | Location |",
            "|---|---|---|---|---|"]
    for i, r in enumerate(refs, 1):
        rows.append(
            f"| {i} | {_safe(r.get('evidence_id'))} | {_safe(r.get('title'))} "
            f"| {_safe(r.get('type'))} | {_safe(r.get('location'))} |"
        )
    return "\n".join(rows) + "\n"


def _write(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")
    print(f"  Generated: {path.name}")


