def gen_evidence_inventory_json(pkg: Dict, out_dir: Path) -> None:
    cert_id = _safe(pkg.get("certification_id"))
    refs    = pkg.get("evidence_references", [])

    items = []
    for r in refs:
        items.append({
            "evidence_id":    _safe(r.get("evidence_id")),
            "title":          _safe(r.get("title")),
            "type":           _safe(r.get("type")),
            "description":    _safe(r.get("description", "")),
            "location":       _safe(r.get("location")),
            "format":         _safe(r.get("format", "")),
            "hash":           _safe(r.get("hash", "")),
            "collected_date": _safe(r.get("collected_date", "")),
            "collected_by":   _safe(r.get("collected_by", "")),
            "status":         "COLLECTED",
            "notes":          _safe(r.get("notes", "")),
        })

    inventory = {
        "certification_id": cert_id,
        "generated_date":   today_iso(),
        "total_items":      len(items),
        "items":            items,
    }
    _write(out_dir / "evidence_inventory.json", json.dumps(inventory, indent=2))


